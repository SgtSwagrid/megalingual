    case EuropeanPortuguese   => "portugais européen"
    case Romanian             => "roumain"
    case Russian              => "russe"
    case Serbian              => "serbe"
    case Slovak               => "slovaque"
    case Slovenian            => "slovène"
    case Spanish              => "espagnol"
    case EuropeanSpanish      => "espagnol d’Espagne"
    case LatinAmericanSpanish => "espagnol d’Amérique latine"
    case Swahili              => "swahili"
