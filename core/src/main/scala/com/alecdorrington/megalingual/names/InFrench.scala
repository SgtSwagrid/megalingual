    case Croatian             => "croate"
    case Czech                => "tchèque"
    case Danish               => "danois"
    case Dutch                => "néerlandais"
    case English              => "anglais"
    case BritishEnglish       => "anglais britannique"
    case AmericanEnglish      => "anglais américain"
    case AustralianEnglish    => "anglais australien"
    case Estonian             => "estonien"
    case Filipino             => "filipino"
    case Finnish              => "finnois"
    case French               => "français"
    case German               => "allemand"
    case GermanGerman         => "allemand (Allemagne)"
    case GermanOfSwitzerland  => "allemand (Suisse)"
    case SwissStandardGerman  => "allemand standard suisse"
    case SwissGerman          => "suisse allemand"
    case Greek                => "grec"
    case Hebrew               => "hébreu"
    case Hindi                => "hindi"
    case Hungarian            => "hongrois"
