package com.alecdorrington.megalingual
package names

import com.alecdorrington.megalingual.Language.*

/** Every language's name in Swedish. */
private[megalingual] object InSwedish:

  def apply(language: Language): String = language match
    case Arabic               => "arabiska"
    case Bengali              => "bengali"
    case Bulgarian            => "bulgariska"
    case Catalan              => "katalanska"
    case Chinese              => "kinesiska"
    case SimplifiedChinese    => "förenklad kinesiska"
    case TraditionalChinese   => "traditionell kinesiska"
    case TaiwaneseChinese     => "traditionell kinesiska (Taiwan)"
    case Cantonese            => "kantonesiska"
    case Croatian             => "kroatiska"
    case Czech                => "tjeckiska"
    case Danish               => "danska"
    case Dutch                => "nederländska"
    case English              => "engelska"
    case BritishEnglish       => "brittisk engelska"
    case AmericanEnglish      => "amerikansk engelska"
    case AustralianEnglish    => "australisk engelska"
    case Estonian             => "estniska"
    case Filipino             => "filippinska"
    case Finnish              => "finska"
    case French               => "franska"
    case German               => "tyska"
    case GermanGerman         => "tyska (Tyskland)"
    case GermanOfSwitzerland  => "tyska (Schweiz)"
    case SwissStandardGerman  => "schweizisk högtyska"
    case SwissGerman          => "schweizertyska"
    case Greek                => "grekiska"
    case Hebrew               => "hebreiska"
    case Hindi                => "hindi"
    case Hungarian            => "ungerska"
    case Indonesian           => "indonesiska"
    case Italian              => "italienska"
    case Japanese             => "japanska"
    case Korean               => "koreanska"
    case Latvian              => "lettiska"
    case Lithuanian           => "litauiska"
    case Malay                => "malajiska"
    case Norwegian            => "norska"
    case Persian              => "persiska"
    case Polish               => "polska"
    case Portuguese           => "portugisiska"
    case BrazilianPortuguese  => "brasiliansk portugisiska"
    case EuropeanPortuguese   => "europeisk portugisiska"
    case Romanian             => "rumänska"
    case Russian              => "ryska"
    case Serbian              => "serbiska"
    case Slovak               => "slovakiska"
    case Slovenian            => "slovenska"
    case Spanish              => "spanska"
    case EuropeanSpanish      => "europeisk spanska"
    case LatinAmericanSpanish => "latinamerikansk spanska"
    case Swahili              => "swahili"
    case Swedish              => "svenska"
    case Tamil                => "tamil"
    case Thai                 => "thailändska"
    case Turkish              => "turkiska"
    case Ukrainian            => "ukrainska"
    case Urdu                 => "urdu"
    case Vietnamese           => "vietnamesiska"
