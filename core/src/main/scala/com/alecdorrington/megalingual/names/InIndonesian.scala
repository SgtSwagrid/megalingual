    case English              => "bahasa Inggris"
    case BritishEnglish       => "bahasa Inggris (Britania)"
    case AmericanEnglish      => "bahasa Inggris (Amerika Serikat)"
    case AustralianEnglish    => "bahasa Inggris (Australia)"
