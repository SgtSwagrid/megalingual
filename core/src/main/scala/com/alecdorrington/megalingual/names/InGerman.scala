    case Croatian             => "Kroatisch"
    case Czech                => "Tschechisch"
    case Danish               => "Dänisch"
    case Dutch                => "Niederländisch"
    case English              => "Englisch"
    case BritishEnglish       => "britisches Englisch"
    case AmericanEnglish      => "amerikanisches Englisch"
    case AustralianEnglish    => "australisches Englisch"
    case Estonian             => "Estnisch"
    case Filipino             => "Filipino"
    case Finnish              => "Finnisch"
    case French               => "Französisch"
    case German               => "Deutsch"
    case GermanGerman         => "Deutsch (Deutschland)"
    case SwissGerman          => "Schweizer Hochdeutsch"
    case Greek                => "Griechisch"
    case Hebrew               => "Hebräisch"
    case Hindi                => "Hindi"
    case Hungarian            => "Ungarisch"
    case Indonesian           => "Indonesisch"
    case Italian              => "Italienisch"
    case Japanese             => "Japanisch"
    case Korean               => "Koreanisch"
    case Latvian              => "Lettisch"
