    case Russian              => "Russisch"
    case Serbian              => "Serbisch"
    case Slovak               => "Slowakisch"
    case Slovenian            => "Slowenisch"
    case Spanish              => "Spanisch"
    case EuropeanSpanish      => "europäisches Spanisch"
    case LatinAmericanSpanish => "lateinamerikanisches Spanisch"
    case Swahili              => "Swahili"
    case Swedish              => "Schwedisch"
    case Tamil                => "Tamil"
    case Thai                 => "Thailändisch"
    case Turkish              => "Türkisch"
    case Ukrainian            => "Ukrainisch"
