package com.alecdorrington.megalingual
package names

import com.alecdorrington.megalingual.Language.*

/** Every language's name in Norwegian. */
private[megalingual] object InNorwegian:

  def apply(language: Language): String = language match
    case Arabic               => "arabisk"
    case Bengali              => "bengali"
    case Bulgarian            => "bulgarsk"
    case Catalan              => "katalansk"
    case Chinese              => "kinesisk"
    case SimplifiedChinese    => "forenklet kinesisk"
    case TraditionalChinese   => "tradisjonell kinesisk"
    case TaiwaneseChinese     => "tradisjonell kinesisk (Taiwan)"
    case Cantonese            => "kantonesisk"
    case Croatian             => "kroatisk"
    case Czech                => "tsjekkisk"
    case Danish               => "dansk"
    case Dutch                => "nederlandsk"
    case English              => "engelsk"
    case BritishEnglish       => "britisk engelsk"
    case AmericanEnglish      => "amerikansk engelsk"
    case AustralianEnglish    => "australsk engelsk"
    case Estonian             => "estisk"
    case Filipino             => "filipino"
    case Finnish              => "finsk"
    case French               => "fransk"
    case German               => "tysk"
    case GermanGerman         => "tysk (Tyskland)"
    case GermanOfSwitzerland  => "tysk (Sveits)"
    case SwissStandardGerman  => "sveitsisk høytysk"
    case SwissGerman          => "sveitsertysk"
    case Greek                => "gresk"
    case Hebrew               => "hebraisk"
    case Hindi                => "hindi"
    case Hungarian            => "ungarsk"
    case Indonesian           => "indonesisk"
    case Italian              => "italiensk"
    case Japanese             => "japansk"
    case Korean               => "koreansk"
    case Latvian              => "latvisk"
    case Lithuanian           => "litauisk"
    case Malay                => "malayisk"
    case Norwegian            => "norsk"
    case Persian              => "persisk"
    case Polish               => "polsk"
    case Portuguese           => "portugisisk"
    case BrazilianPortuguese  => "brasiliansk portugisisk"
    case EuropeanPortuguese   => "europeisk portugisisk"
    case Romanian             => "rumensk"
    case Russian              => "russisk"
    case Serbian              => "serbisk"
    case Slovak               => "slovakisk"
    case Slovenian            => "slovensk"
    case Spanish              => "spansk"
    case EuropeanSpanish      => "europeisk spansk"
    case LatinAmericanSpanish => "latinamerikansk spansk"
    case Swahili              => "swahili"
    case Swedish              => "svensk"
    case Tamil                => "tamil"
    case Thai                 => "thai"
    case Turkish              => "tyrkisk"
    case Ukrainian            => "ukrainsk"
    case Urdu                 => "urdu"
    case Vietnamese           => "vietnamesisk"
