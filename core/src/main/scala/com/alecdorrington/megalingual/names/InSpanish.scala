package com.alecdorrington.megalingual
package names

import com.alecdorrington.megalingual.Language.*

/** Every language's name in Spanish. */
private[megalingual] object InSpanish:

  def apply(language: Language): String = language match
    case Arabic               => "árabe"
    case Bengali              => "bengalí"
    case Bulgarian            => "búlgaro"
    case Catalan              => "catalán"
    case Chinese              => "chino"
    case SimplifiedChinese    => "chino simplificado"
    case TraditionalChinese   => "chino tradicional"
    case Cantonese            => "cantonés"
    case Croatian             => "croata"
    case Czech                => "checo"
    case Danish               => "danés"
    case Dutch                => "neerlandés"
    case English              => "inglés"
    case BritishEnglish       => "inglés británico"
    case AmericanEnglish      => "inglés estadounidense"
    case AustralianEnglish    => "inglés australiano"
    case Estonian             => "estonio"
    case Filipino             => "filipino"
    case Finnish              => "finlandés"
    case French               => "francés"
    case German               => "alemán"
    case GermanGerman         => "alemán (Alemania)"
    case SwissGerman          => "alemán estándar suizo"
    case Greek                => "griego"
    case Hebrew               => "hebreo"
    case Hindi                => "hindi"
    case Hungarian            => "húngaro"
    case Indonesian           => "indonesio"
    case Italian              => "italiano"
    case Japanese             => "japonés"
    case Korean               => "coreano"
    case Latvian              => "letón"
    case Lithuanian           => "lituano"
    case Malay                => "malayo"
    case Norwegian            => "noruego"
    case Persian              => "persa"
    case Polish               => "polaco"
    case Portuguese           => "portugués"
    case BrazilianPortuguese  => "portugués de Brasil"
    case EuropeanPortuguese   => "portugués de Portugal"
    case Romanian             => "rumano"
    case Russian              => "ruso"
    case Serbian              => "serbio"
    case Slovak               => "eslovaco"
    case Slovenian            => "esloveno"
    case Spanish              => "español"
    case EuropeanSpanish      => "español de España"
    case LatinAmericanSpanish => "español latinoamericano"
    case Swahili              => "suajili"
    case Swedish              => "sueco"
    case Tamil                => "tamil"
    case Thai                 => "tailandés"
    case Turkish              => "turco"
    case Ukrainian            => "ucraniano"
    case Urdu                 => "urdu"
    case Vietnamese           => "vietnamita"
