    case Czech                => "czeski"
    case Danish               => "duński"
    case Dutch                => "niderlandzki"
    case English              => "angielski"
    case BritishEnglish       => "angielski brytyjski"
    case AmericanEnglish      => "angielski amerykański"
    case AustralianEnglish    => "angielski australijski"
    case Estonian             => "estoński"
    case Filipino             => "filipiński"
    case Finnish              => "fiński"
    case French               => "francuski"
    case German               => "niemiecki"
    case GermanGerman         => "niemiecki (Niemcy)"
    case SwissGerman          => "wysokoniemiecki szwajcarski"
    case Greek                => "grecki"
    case Hebrew               => "hebrajski"
    case Hindi                => "hindi"
